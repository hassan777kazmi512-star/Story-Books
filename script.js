const mouseGlow =
    document.getElementById("mouseGlow");


document.addEventListener(
    "mousemove",
    function(event) {

        mouseGlow.style.left =
            event.clientX + "px";

        mouseGlow.style.top =
            event.clientY + "px";

    }
);


/* Make glow bigger over clickable elements */

const clickableElements =
    document.querySelectorAll(
        "button, a, .book-card"
    );


clickableElements.forEach(
    function(element) {

        element.addEventListener(
            "mouseenter",
            function() {

                mouseGlow.style.width = "60px";

                mouseGlow.style.height = "60px";

            }
        );


        element.addEventListener(
            "mouseleave",
            function() {

                mouseGlow.style.width = "35px";

                mouseGlow.style.height = "35px";

            }
        );

    }
);